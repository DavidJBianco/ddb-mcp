import { readFile, writeFile } from "node:fs/promises";

const packageUrl = new URL("../package.json", import.meta.url);
const outputUrl = new URL("../cmd/mysterium-auth/version.go", import.meta.url);
const { version } = JSON.parse(await readFile(packageUrl, "utf8"));

if (typeof version !== "string" || version.length === 0) {
  throw new Error("package.json does not contain a valid version");
}

const expected = `// Code generated by scripts/sync-auth-version.mjs; DO NOT EDIT.

package main

var version = ${JSON.stringify(version)}
`;

if (process.argv.includes("--check")) {
  const actual = await readFile(outputUrl, "utf8").catch(() => "");
  if (actual !== expected) {
    console.error("cmd/mysterium-auth/version.go is out of sync; run make helper");
    process.exitCode = 1;
  }
} else {
  const actual = await readFile(outputUrl, "utf8").catch(() => "");
  if (actual !== expected) {
    await writeFile(outputUrl, expected);
  }
}
